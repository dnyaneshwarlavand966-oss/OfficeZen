object PdfAndCsvExporter {

  fun generatePayslipPdf(
    context: Context,
    office: Office,
    payroll: EmployeePayrollSummary,
  ): File {
    val pdf = PdfDocument()
    val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
    val page = pdf.startPage(pageInfo)
    val canvas: Canvas = page.canvas

    val titlePaint =
      Paint().apply {
        color = Color.rgb(15, 92, 92)
        textSize = 20f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      }
    val headingPaint =
      Paint().apply {
        color = Color.rgb(24, 34, 34)
        textSize = 14f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      }
    val bodyPaint =
      Paint().apply {
        color = Color.rgb(40, 50, 50)
        textSize = 12f
      }
    val linePaint =
      Paint().apply {
        color = Color.rgb(210, 210, 200)
        strokeWidth = 1.5f
      }

    var y = 54f
    canvas.drawText("${office.name} — Salary Payslip", 44f, y, titlePaint)
    y += 24f
    canvas.drawText("Month: ${payroll.monthKey}", 44f, y, bodyPaint)
    y += 14f
    canvas.drawLine(44f, y, 551f, y, linePaint)
    y += 26f

    canvas.drawText("Employee: ${payroll.member.displayName}", 44f, y, headingPaint)
    y += 20f
    canvas.drawText(
      "Role: ${payroll.member.role.uppercase()}  |  Designation: ${payroll.member.designation}",
      44f,
      y,
      bodyPaint,
    )
    y += 26f

    canvas.drawText("Attendance Summary", 44f, y, headingPaint)
    y += 20f
    canvas.drawText(
      "Working Days: ${payroll.workingDaysInMonth}   Present: ${payroll.presentDays}   On-Time: ${payroll.onTimeDays}",
      44f,
      y,
      bodyPaint,
    )
    y += 18f
    canvas.drawText(
      "Late Marks: ${payroll.lateMarks}   Late Penalty Half-Days (${office.lateMarksPerHalfDay} late = 1/2): ${payroll.latePenaltyHalfDays}   Total Half-Days: ${payroll.totalHalfDays}",
      44f,
      y,
      bodyPaint,
    )
    y += 18f
    canvas.drawText(
      "Paid Leave: ${payroll.paidLeaveDays}d   Unpaid Leave: ${payroll.unpaidLeaveDays}d   Absent: ${payroll.absentDays}d   Overtime: ${payroll.overtimeMinutes} min",
      44f,
      y,
      bodyPaint,
    )
    y += 28f

    canvas.drawLine(44f, y, 551f, y, linePaint)
    y += 24f
    canvas.drawText("Earnings & Deductions (INR)", 44f, y, headingPaint)
    y += 22f

    fun row(label: String, value: String) {
      canvas.drawText(label, 44f, y, bodyPaint)
      canvas.drawText(value, 420f, y, bodyPaint)
      y += 20f
    }

    row("Monthly Base Salary", "Rs. ${payroll.monthlyBaseSalaryInr.roundToInt()}")
    row("Overtime Pay (+)", "Rs. ${payroll.overtimePayInr.roundToInt()}")
    row("Bonuses (+)", "Rs. ${payroll.bonusesInr.roundToInt()}")
    row("Attendance / Late / Leave Deduction (-)", "Rs. ${payroll.attendanceDeductionInr.roundToInt()}")
    row("Salary Advances (-)", "Rs. ${payroll.advancesInr.roundToInt()}")
    row("Other Deductions (-)", "Rs. ${payroll.manualDeductionsInr.roundToInt()}")
    row("Tea/Coffee Logged (${payroll.teaCups} cups, info)", "Rs. ${payroll.teaEstimatedCostInr.roundToInt()}")

    y += 8f
    canvas.drawLine(44f, y, 551f, y, linePaint)
    y += 26f
    canvas.drawText("NET PAYABLE SALARY", 44f, y, titlePaint)
    canvas.drawText("Rs. ${payroll.netPayableInr.roundToInt()}", 410f, y, titlePaint)

    y += 42f
    canvas.drawText("Generated by OfficeZen", 44f, y, bodyPaint)
    pdf.finishPage(page)

    val dir = File(context.cacheDir, "exports").apply { mkdirs() }
    val safeName = payroll.member.displayName.replace(Regex("[^a-zA-Z0-9]"), "_")
    val file = File(dir, "Payslip_${safeName}_${payroll.monthKey}.pdf")
    FileOutputStream(file).use { pdf.writeTo(it) }
    pdf.close()
    return file
  }

  fun generateMonthEndPdf(
    context: Context,
    office: Office,
    summary: MonthEndSummary,
  ): File {
    val pdf = PdfDocument()
    val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
    val page = pdf.startPage(pageInfo)
    val canvas = page.canvas

    val titlePaint =
      Paint().apply {
        color = Color.rgb(15, 92, 92)
        textSize = 18f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      }
    val headingPaint =
      Paint().apply {
        color = Color.rgb(24, 34, 34)
        textSize = 13f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
      }
    val bodyPaint =
      Paint().apply {
        color = Color.rgb(40, 50, 50)
        textSize = 11f
      }

    var y = 48f
    canvas.drawText("${office.name} — Month-End Owner Report (${summary.monthKey})", 40f, y, titlePaint)
    y += 24f
    canvas.drawText(
      "Total Salary Bill: Rs. ${summary.totalSalaryPayableInr.roundToInt()}   |   Total Present Days: ${summary.totalPresentDays}   |   Late Marks: ${summary.totalLateMarks}",
      40f,
      y,
      bodyPaint,
    )
    y += 18f
    canvas.drawText(
      "Tea Cups: ${summary.totalTeaCups}   |   Coffee Cups: ${summary.totalCoffeeCups}   |   Pantry Spend: Rs. ${summary.totalPantryPurchaseInr.roundToInt()} (Avg Rs. ${summary.effectiveCostPerCupInr}/cup)",
      40f,
      y,
      bodyPaint,
    )
    y += 28f

    canvas.drawText("Employee Breakdown", 40f, y, headingPaint)
    y += 20f
    canvas.drawText("Name", 40f, y, headingPaint)
    canvas.drawText("Present", 210f, y, headingPaint)
    canvas.drawText("Late/Half", 275f, y, headingPaint)
    canvas.drawText("Tea Cups", 355f, y, headingPaint)
    canvas.drawText("Net Pay", 445f, y, headingPaint)
    y += 18f

    summary.employeePayrolls.take(28).forEach { p ->
      canvas.drawText(p.member.displayName.take(24), 40f, y, bodyPaint)
      canvas.drawText("${p.presentDays}", 215f, y, bodyPaint)
      canvas.drawText("${p.lateMarks}L / ${p.totalHalfDays}H", 275f, y, bodyPaint)
      canvas.drawText("${p.teaCups}", 365f, y, bodyPaint)
      canvas.drawText("Rs. ${p.netPayableInr.roundToInt()}", 445f, y, bodyPaint)
      y += 16f
    }

    pdf.finishPage(page)
    val dir = File(context.cacheDir, "exports").apply { mkdirs() }
    val file = File(dir, "OfficeZen_MonthEnd_${summary.monthKey}.pdf")
    FileOutputStream(file).use { pdf.writeTo(it) }
    pdf.close()
    return file
  }

  fun generateMonthEndCsv(
    context: Context,
    office: Office,
    summary: MonthEndSummary,
  ): File {
    val sb = StringBuilder()
    // UTF-8 BOM for clean Microsoft Excel rendering of Indian scripts & ₹
    sb.append('\uFEFF')
    sb.appendLine("Office,${csvEscape(office.name)},Month,${summary.monthKey}")
    sb.appendLine("Total Salary Payable (INR),${summary.totalSalaryPayableInr.roundToInt()},Tea Cups,${summary.totalTeaCups},Coffee Cups,${summary.totalCoffeeCups},Pantry Expense (INR),${summary.totalPantryPurchaseInr.roundToInt()}")
    sb.appendLine()
    sb.appendLine("Employee,Role,Base Salary,Present Days,Late Marks,Half Days,Paid Leave,Unpaid Leave,Overtime Min,Overtime Pay,Advances,Deductions,Bonuses,Net Payable (INR),Tea Cups,Tea Est Cost (INR)")
    summary.employeePayrolls.forEach { p ->
      sb.appendLine(
        listOf(
          csvEscape(p.member.displayName),
          p.member.role,
          p.monthlyBaseSalaryInr.roundToInt().toString(),
          p.presentDays.toString(),
          p.lateMarks.toString(),
          p.totalHalfDays.toString(),
          p.paidLeaveDays.toString(),
          p.unpaidLeaveDays.toString(),
          p.overtimeMinutes.toString(),
          p.overtimePayInr.roundToInt().toString(),
          p.advancesInr.roundToInt().toString(),
          (p.attendanceDeductionInr + p.manualDeductionsInr).roundToInt().toString(),
          p.bonusesInr.roundToInt().toString(),
          p.netPayableInr.roundToInt().toString(),
          p.teaCups.toString(),
          p.teaEstimatedCostInr.roundToInt().toString(),
        ).joinToString(",")
      )
    }

    val dir = File(context.cacheDir, "exports").apply { mkdirs() }
    val file = File(dir, "OfficeZen_Report_${summary.monthKey}.csv")
    file.writeText(sb.toString(), Charsets.UTF_8)
    return file
  }

  fun shareFile(
    context: Context,
    file: File,
    mimeType: String,
    subject: String,
    bodyText: String,
    targetPackage: String? = null,
    emailRecipient: String? = null,
  ) {
    val uri: Uri =
      FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
    val intent =
      Intent(Intent.ACTION_SEND).apply {
        type = mimeType
        putExtra(Intent.EXTRA_STREAM, uri)
        putExtra(Intent.EXTRA_SUBJECT, subject)
        putExtra(Intent.EXTRA_TEXT, bodyText)
        if (!emailRecipient.isNullOrBlank()) {
          putExtra(Intent.EXTRA_EMAIL, arrayOf(emailRecipient))
        }
        addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        if (!targetPackage.isNullOrBlank()) {
          `package` = targetPackage
        }
      }
    try {
      context.startActivity(Intent.createChooser(intent, subject).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    } catch (_: Exception) {
      val fallback =
        Intent(Intent.ACTION_SEND).apply {
          type = mimeType
          putExtra(Intent.EXTRA_STREAM, uri)
          putExtra(Intent.EXTRA_SUBJECT, subject)
          putExtra(Intent.EXTRA_TEXT, bodyText)
          addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
      context.startActivity(Intent.createChooser(fallback, subject).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
    }
  }

  fun buildMonthEndSummaryText(office: Office, summary: MonthEndSummary): String =
    buildString {
      appendLine("*${office.name} — Month-End Report (${summary.monthKey})*")
      appendLine("Total Salary Bill: Rs. ${summary.totalSalaryPayableInr.roundToInt()}")
      appendLine("Total Present Days: ${summary.totalPresentDays} | Late Marks: ${summary.totalLateMarks} | Half-Days: ${summary.totalHalfDays}")
      appendLine("Tea/Coffee: ${summary.totalTeaCups} Tea + ${summary.totalCoffeeCups} Coffee | Spend: Rs. ${summary.totalPantryPurchaseInr.roundToInt()}")
    }

  private fun csvEscape(value: String): String {
    val escaped = value.replace("\"", "\"\"")
    return "\"$escaped\""
  }
}
